// Lucide icons by their Lucide names, the names phramer-overlay's `ICONS`
// table uses, so the editor and the overlay show the same icon for a tool.

import {
  ArrowDown,
  ArrowUp,
  ArrowUpRight,
  Bold,
  Check,
  Circle,
  Contrast,
  Copy,
  Crop,
  ExternalLink,
  FileImage,
  FolderDown,
  Grid2x2,
  Grid3x3,
  Hand,
  Hash,
  Highlighter,
  Italic,
  ImagePlus,
  type LucideIcon,
  Maximize2,
  Minus,
  Move,
  Pencil,
  Pin,
  Pipette,
  Plus,
  RectangleHorizontal,
  Redo2,
  Save,
  SaveAll,
  Scan,
  ScanText,
  Search,
  Shapes,
  Slash,
  Square,
  SquareDashed,
  SquarePen,
  Strikethrough,
  Trash2,
  Type,
  Underline,
  Undo2,
  X,
  ZoomIn,
  ZoomOut,
} from "lucide-react";

export const ICONS: Record<string, LucideIcon> = {
  // phramer-overlay's table
  "arrow-down": ArrowDown,
  "arrow-up": ArrowUp,
  "arrow-up-right": ArrowUpRight,
  bold: Bold,
  italic: Italic,
  strikethrough: Strikethrough,
  underline: Underline,
  check: Check,
  circle: Circle,
  contrast: Contrast,
  copy: Copy,
  "external-link": ExternalLink,
  "file-image": FileImage,
  "grid-3x3": Grid3x3,
  hand: Hand,
  hash: Hash,
  highlighter: Highlighter,
  minus: Minus,
  move: Move,
  pencil: Pencil,
  pin: Pin,
  plus: Plus,
  "rectangle-horizontal": RectangleHorizontal,
  "redo-2": Redo2,
  save: Save,
  "scan-text": ScanText,
  shapes: Shapes,
  slash: Slash,
  square: Square,
  "square-pen": SquarePen,
  type: Type,
  "undo-2": Undo2,
  x: X,
  // The editor's own
  crop: Crop,
  pipette: Pipette,
  "zoom-in": ZoomIn,
  "zoom-out": ZoomOut,
  scan: Scan,
  "square-dashed": SquareDashed,
  "save-all": SaveAll,
  "maximize-2": Maximize2,
  "folder-down": FolderDown,
  "trash-2": Trash2,
  search: Search,
  "grid-2x2": Grid2x2,
  "image-plus": ImagePlus,
};

export function Icon({ name }: { name: string }) {
  const Glyph = ICONS[name];
  return Glyph ? <Glyph className="icon" aria-hidden="true" strokeWidth={2} /> : null;
}
